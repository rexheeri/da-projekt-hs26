"""Quality report of the full build (Phase 3): what is complete, what was lost, and why.

Checks (all aggregations in SQL, counts of the filter steps from data/processed/build_log.csv):
- missing days: study days without arrivals, days with an ERROR in the build
- duplicates: same service_date, trip, stop and scheduled arrival more than once
- filter losses summed over all days (cancelled, not measured, other category, ...)
- stops without weather station, arrivals without weather value or calendar day
- rows per winter and traffic type

Usage (from the repo root):  python -m src.quality_report
Output: printed and saved to data/processed/quality_report.md
"""
import pandas as pd

from src.build_db import BUILD_LOG, study_days
from src.db import query
from src.paths import PROCESSED_DIR


def markdown_table(df):
    """DataFrame -> Markdown table (own helper, avoids the extra package 'tabulate')."""
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "---|" * len(df.columns)
    body = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *body])


def main():
    lines = ["# Quality report (generated by src/quality_report.py)", ""]

    def add(title, df):
        """Append a titled table to the report."""
        lines.extend([f"## {title}", "", markdown_table(df), ""])

    # 1. Missing days
    days = set(study_days())
    loaded = set(query("SELECT DISTINCT service_date FROM arrivals")["service_date"])
    log = pd.read_csv(BUILD_LOG)
    log = log.drop_duplicates(["step", "metric"], keep="last")   # a re-run day counts once
    errors = sorted(set(log.loc[log.metric == "error", "step"]) - loaded)
    add("Days", pd.DataFrame({
        "study days": [len(days)], "days with arrivals": [len(days & loaded)],
        "missing days": [", ".join(sorted(days - loaded)) or "none"],
        "days with build error (not loaded)": [", ".join(errors) or "none"]}))

    # 2. Duplicates (SQL GROUP BY ... HAVING)
    dup = query("""
        SELECT COUNT(*) AS duplicate_keys FROM (
            SELECT service_date, trip_id, bpuic, sched_arr_utc
            FROM arrivals GROUP BY service_date, trip_id, bpuic, sched_arr_utc HAVING COUNT(*) > 1) AS d""")
    add("Duplicates (same day, trip, stop and scheduled arrival)", dup)

    # 3. Filter losses over all days (from the build log, one value per day and metric)
    day_rows = log[log.step.isin(days)]
    metrics = ["raw_rows", "raw_trip_rows", "removed_outside_area", "area_rows", "removed_no_scheduled_arrival",
               "removed_pass_through", "removed_cancelled", "removed_not_real", "removed_other_category",
               "removed_implausible_delay", "removed_duplicate", "times_not_convertible", "arrivals"]
    totals = day_rows[day_rows.metric.isin(metrics)].groupby("metric")["value"].sum().reindex(metrics)
    totals = totals.astype("Int64").reset_index().rename(columns={"value": "rows (all days)"})
    add("Filter steps summed over all days", totals)

    # 4. Join completeness
    join = query("""
        SELECT COUNT(*) AS arrivals,
               SUM(CASE WHEN precip_mm IS NULL THEN 1 ELSE 0 END) AS without_precipitation,
               SUM(CASE WHEN temp_c IS NULL THEN 1 ELSE 0 END)    AS without_temperature,
               SUM(CASE WHEN precip_cat IS NULL THEN 1 ELSE 0 END) AS without_precip_cat,
               SUM(CASE WHEN holiday IS NULL THEN 1 ELSE 0 END)    AS without_calendar
        FROM analysis_base""")
    stops = query("""
        SELECT (SELECT COUNT(*) FROM stops) AS stops,
               (SELECT COUNT(*) FROM stops s LEFT JOIN stop_station ss ON ss.bpuic = s.bpuic
                WHERE ss.precip_station IS NULL OR ss.temp_station IS NULL) AS stops_without_station,
               (SELECT COUNT(DISTINCT bpuic) FROM arrivals) AS stops_with_arrivals""")
    add("Join completeness (analysis_base)", join)
    add("Stops", stops)

    # 5. Rows per winter, traffic type and weather class
    per = query("""
        SELECT winter, traffic_type, precip_cat, COUNT(*) AS arrivals,
               COUNT(DISTINCT weather_hour_utc) AS weather_hours, ROUND(100.0 * AVG(delayed), 1) AS delay_rate_pct
        FROM analysis_base GROUP BY winter, traffic_type, precip_cat ORDER BY winter, traffic_type, precip_cat""")
    add("Rows per winter, traffic type and weather class", per)

    text = "\n".join(lines)
    (PROCESSED_DIR / "quality_report.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
